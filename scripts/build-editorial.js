/* Deterministic outputs from the reviewed editorial registry and static routes. */
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const site = path.join(root, 'SITE');
const origin = 'https://japaorelativo.com';
const source = JSON.parse(fs.readFileSync(path.join(site, 'data/editorial-posts.json'), 'utf8'));
const covers = JSON.parse(fs.readFileSync(path.join(site, 'data/editorial-covers.json'), 'utf8')).posts;
const home = JSON.parse(fs.readFileSync(path.join(site, 'data/editorial-home.json'), 'utf8'));
const topics = JSON.parse(fs.readFileSync(path.join(site, 'data/editorial-topics.json'), 'utf8'));
const aliases = {
  'o-japao-entra-no-outono-antes-de-esfriar': 'japao-outono-antes-de-esfriar',
  'japao-alem-cartao-postal-viagem': 'japao-alem-cartao-postal-viagem-melhor'
};
function walk(dir) {
  return fs.readdirSync(dir,{withFileTypes:true}).flatMap(e=>e.isDirectory()?walk(path.join(dir,e.name)):[path.join(dir,e.name)]);
}
function routeFor(id) {
  return fs.existsSync(path.join(site,id,'index.html')) ? '/' + id + '/' : '/#' + id;
}
function normalizeHref(href) {
  if (/^(?:[a-z]+:|\/\/)/i.test(href)) return href;
  const id = href.replace(/^(?:\.\.\/|\.\/|\/|#)+/,'').replace(/\/$/,'');
  const actual = aliases[id] || id;
  return source[actual] ? routeFor(actual) : href;
}
const output = {};
const escapeAttr = s => String(s).replaceAll('&','&amp;').replaceAll('"','&quot;').replaceAll('<','&lt;');
function primaryCover(html, cover, relative) {
  let changed = false;
  // Only replace the first editorial image. Logos and subsequent documentary images stay intact.
  html = html.replace(/<img\b[^>]*>/gi, tag => {
    if (changed || !/\bsrc=["'](?:(?:[^"']*\/)?assets\/covers\/)/i.test(tag)) return tag;
    changed = true;
    return '<img data-jr-cover="'+cover.kind+'" src="'+relative+escapeAttr(cover.src)+'" alt="'+escapeAttr(cover.alt)+'" loading="lazy" decoding="async">';
  });
  if (changed && cover.kind === 'illustration') {
    html = html.replace(/(<figure\b[^>]*>\s*<img\b[^>]*data-jr-cover=["']illustration["'][^>]*>\s*)<figcaption>[\s\S]*?<\/figcaption>/i,
      '$1<figcaption>Ilustração editorial conceitual. '+escapeAttr(cover.alt.replace(/^Ilustração editorial: /,''))+'</figcaption>');
  }
  return html;
}
for (const [id,post] of Object.entries(source)) {
  if (!/^[\p{L}\p{N}]+(?:-[\p{L}\p{N}]+)*$/u.test(id) || !post.title || !post.content) throw Error('Invalid editorial record: '+id);
  const cover = covers[id];
  if (!cover || !cover.src || !cover.alt) throw Error('Missing reviewed cover: '+id);
  const replaced = cover.review === 'replaced-subject' || cover.review === 'rebound-contextual';
  const content = replaced ? primaryCover(post.content, cover, '') : post.content;
  output[id] = {...post, id, thumb:cover.src, cover, canonicalPath:routeFor(id), content:content.replace(/href=(["'])(.*?)\1/g,(_,q,href)=>'href='+q+normalizeHref(href)+q)};
  const file = path.join(site,id,'index.html');
  if (replaced && fs.existsSync(file)) {
    let html = primaryCover(fs.readFileSync(file,'utf8'),cover,'../');
    const image = /^https:\/\//.test(cover.src) ? cover.src : origin+'/'+cover.src;
    html = html.replace(/(<meta\b[^>]*(?:property=["']og:image["']|name=["']twitter:image["'])[^>]*content=)["'][^"']*["']/gi,'$1"'+image+'"');
    if (!/name=["']twitter:image["']/.test(html)) html=html.replace('</head>','  <meta name="twitter:image" content="'+image+'">\n</head>');
    html = html.replace(/("image"\s*:\s*")[^"]*(")/g,'$1'+image+'$2');
    fs.writeFileSync(file,html);
  }
}
// Every article has one reviewed editorial home: topic, dated archive or Japanese.
const members = topics.topics.flatMap(topic => {
  if (!topic.id || !topic.label || !topic.postIds.length) throw Error('Empty editorial topic');
  return topic.postIds;
}).concat(topics.newsIds, topics.languageIds);
if (new Set(topics.topics.map(t => t.id)).size !== topics.topics.length) throw Error('Duplicate topic identifier');
if (members.length !== Object.keys(output).length || new Set(members).size !== members.length || members.some(id => !output[id])) throw Error('Editorial topics must cover the active archive exactly once');
for (const id of home.selected) if (!output[id]) throw Error('Unknown home selection: '+id);
fs.writeFileSync(path.join(site,'assets/data/editorial-posts.js'),'/* Generated by scripts/build-editorial.js. Edit SITE/data/editorial-posts.json, editorial-covers.json, editorial-home.json and editorial-topics.json. */\nwindow.JR_POSTS = '+JSON.stringify(output)+';\nwindow.JR_HOME = '+JSON.stringify(home)+';\nwindow.JR_TOPICS = '+JSON.stringify(topics)+';\n');
// Render the real opening at build time: useful without JS and stable before hydration.
const lead = output[home.selected[0]];
const copy = home.copy[lead.id] || lead;
const homeFile = path.join(site, 'index.html');
let homeHtml = fs.readFileSync(homeFile, 'utf8');
const preview = lead.cover.preview || lead.cover.src;
const image = '<a class="hero-bg-slide active" href="'+escapeAttr(lead.canonicalPath)+'" aria-label="'+escapeAttr(lead.title)+'"><img src="'+escapeAttr(preview)+'" alt="" width="4" height="5" fetchpriority="high" decoding="async"></a>';
homeHtml = homeHtml.replace(/(<div class="hero-bg-slides" id="heroSlides">)[\s\S]*?(<\/div>)/, '$1'+image+'$2');
homeHtml = homeHtml.replace(/(<span class="hero-slide-cat" id="ht-cat">)[\s\S]*?(<\/span>)/, '$1'+escapeAttr(lead.tag)+'$2');
homeHtml = homeHtml.replace(/(<h1 class="hero-slide-title" id="ht-title">)[\s\S]*?(<\/h1>)/, '$1'+escapeAttr(copy.title || lead.title)+'$2');
homeHtml = homeHtml.replace(/(<p class="hero-slide-sub" id="ht-sub">)[\s\S]*?(<\/p>)/, '$1'+escapeAttr(copy.subtitle || lead.subtitle || '')+'$2');
const topicButtons = (nav) => topics.topics.map(topic => {
  const count = topic.postIds.length + (topic.postIds.length === 1 ? ' matéria' : ' matérias');
  return '<button type="button" data-jr-topic="'+escapeAttr(topic.id)+'"><span>'+escapeAttr(topic.label)+'</span><small>'+count+'</small>'+(nav ? '' : '<span class="jr-topic-arrow" aria-hidden="true">↗</span>')+'</button>';
}).join('\n');
homeHtml = homeHtml.replace(/(<div class="jr-nav-topic-grid">)[\s\S]*?(<\/div>)/, (_,start,end) => start+'\n'+topicButtons(true)+'\n'+end);
homeHtml = homeHtml.replace(/(<div class="jr-topic-grid">)[\s\S]*?(<\/div>)/, (_,start,end) => start+'\n'+topicButtons(false)+'\n'+end);
fs.writeFileSync(homeFile, homeHtml);
// Build the independently branded ONI area before collecting site routes.
require('./build-oni.js');
const urls=[];
for (const file of walk(site).filter(p=>p.endsWith('.html'))) {
  const html=fs.readFileSync(file,'utf8');
  if (/<meta\b[^>]*name=["']robots["'][^>]*content=["'][^"']*noindex/i.test(html)) continue;
  const rel=path.relative(site,file).replaceAll(path.sep,'/');
  const route=rel==='index.html'?'/':rel.replace(/index\.html$/,'');
  const expected=origin+'/'+route.replace(/^\//,'');
  const canonical=html.match(/<link\b[^>]*rel=["']canonical["'][^>]*href=["']([^"']+)/i)?.[1];
  if(canonical&&canonical!==expected) throw Error('Canonical mismatch '+rel+': '+canonical);
  urls.push(expected);
}
const xmlEscape=s=>s.replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;');
fs.writeFileSync(path.join(site,'sitemap.xml'),'<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'+[...new Set(urls)].sort().map(url=>'  <url><loc>'+xmlEscape(url)+'</loc></url>').join('\n')+'\n</urlset>\n');
console.log('Built '+Object.keys(output).length+' editorial records and '+urls.length+' indexable routes.');
