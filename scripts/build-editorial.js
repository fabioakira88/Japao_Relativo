/* Deterministic outputs from the reviewed editorial registry and static routes. */
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const site = path.join(root, 'SITE');
const origin = 'https://japaorelativo.com';
const source = JSON.parse(fs.readFileSync(path.join(site, 'data/editorial-posts.json'), 'utf8'));
const aliases = {
  'o-japao-entra-no-outono-antes-de-esfriar': 'japao-outono-antes-de-esfriar',
  'japao-alem-cartao-postal-viagem': 'japao-alem-cartao-postal-viagem-melhor'
};
function walk(dir) {
  return fs.readdirSync(dir,{withFileTypes:true}).flatMap(e=>e.isDirectory()?walk(path.join(dir,e.name)):[path.join(dir,e.name)]);
}
function routeFor(id) {
  return fs.existsSync(path.join(site,id,'index.html')) ? '/' + id + '/' : '/#' + id;
}
function normalizeHref(href) {
  if (/^(?:[a-z]+:|\/\/)/i.test(href)) return href;
  const id = href.replace(/^(?:\.\.\/|\.\/|\/|#)+/,'').replace(/\/$/,'');
  const actual = aliases[id] || id;
  return source[actual] ? routeFor(actual) : href;
}
const output = {};
for (const [id,post] of Object.entries(source)) {
  if (!/^[\p{L}\p{N}]+(?:-[\p{L}\p{N}]+)*$/u.test(id) || !post.title || !post.content) throw Error('Invalid editorial record: '+id);
  output[id] = {...post, canonicalPath:routeFor(id), content:post.content.replace(/href=(["'])(.*?)\1/g,(_,q,href)=>'href='+q+normalizeHref(href)+q)};
}
fs.writeFileSync(path.join(site,'assets/data/editorial-posts.js'),'/* Generated by scripts/build-editorial.js. Edit SITE/data/editorial-posts.json. */\nwindow.JR_POSTS = '+JSON.stringify(output)+';\n');
const urls=[];
for (const file of walk(site).filter(p=>p.endsWith('.html'))) {
  const html=fs.readFileSync(file,'utf8');
  if (/<meta\b[^>]*name=["']robots["'][^>]*content=["'][^"']*noindex/i.test(html)) continue;
  const rel=path.relative(site,file).replaceAll(path.sep,'/');
  const route=rel==='index.html'?'/':rel.replace(/index\.html$/,'');
  const expected=origin+'/'+route.replace(/^\//,'');
  const canonical=html.match(/<link\b[^>]*rel=["']canonical["'][^>]*href=["']([^"']+)/i)?.[1];
  if(canonical&&canonical!==expected) throw Error('Canonical mismatch '+rel+': '+canonical);
  urls.push(expected);
}
const xmlEscape=s=>s.replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;');
fs.writeFileSync(path.join(site,'sitemap.xml'),'<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'+[...new Set(urls)].sort().map(url=>'  <url><loc>'+xmlEscape(url)+'</loc></url>').join('\n')+'\n</urlset>\n');
console.log('Built '+Object.keys(output).length+' editorial records and '+urls.length+' indexable routes.');
